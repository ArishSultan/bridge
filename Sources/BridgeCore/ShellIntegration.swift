import Foundation

/// Bridge's shell integration for zsh and bash, replacing Ghostty's own.
///
/// Small generated startup files load the user's own startup files first, then install hooks
/// that:
/// - mark prompts and commands with OSC 133 and report the folder with OSC 7, which libghostty
///   uses for jumping between prompts and for finished-command reports;
/// - report each command, its exit status and folder to the app over a unix socket (zsh, with its
///   built-in `zsocket`) or through the `bridge-helper` program (bash), for history, attention
///   and completions;
/// - apply the prompt settings, re-reading a prompt file before every prompt so a new style
///   applies without restarting the shell.
///
/// Messages are fields separated by U+001F, each message ended by a NUL byte.
public enum ShellIntegration {
    /// Where the scripts live. v1 owns `shell/`; v2 keeps its own so the two never overwrite
    /// each other's scripts.
    public static var directory: URL { Settings.configDirectory.appendingPathComponent("shell-v2") }

    /// Environment for a terminal's shell.
    public struct Environment: Equatable, Sendable {
        /// The command to run instead of the login shell (nil: the login shell).
        public var command: String?
        public var variables: [String: String]
    }

    /// The shell's name (`zsh`, `bash`…) for a command or the login shell.
    public static func shellName(_ shell: String) -> String {
        (shell.split(separator: " ").first.map(String.init) ?? shell).split(separator: "/").last.map(String.init) ?? shell
    }

    /// How to start an interactive shell with the integration. `shell` is the configured shell
    /// command (empty for the login shell); `loginShell` the program it resolves to.
    public static func launch(shell: String, loginShell: String, socket: String, token: String, helper: String?) -> Environment {
        let shell = shell.trimmingCharacters(in: .whitespaces)
        var variables = [
            "BRIDGE_SOCKET": socket,
            "BRIDGE_PANE": token,
            "BRIDGE_PROMPT_DIR": directory.path,
            "TERM_PROGRAM": "Bridge",
        ]
        if let helper { variables["BRIDGE_HELPER"] = helper }

        switch shellName(shell.isEmpty ? loginShell : shell) {
        case "zsh":
            if let user = ProcessInfo.processInfo.environment["ZDOTDIR"] {
                variables["BRIDGE_USER_ZDOTDIR"] = user
            }
            variables["ZDOTDIR"] = directory.appendingPathComponent("zsh").path
            variables["BRIDGE_INTEGRATION"] = directory.appendingPathComponent("integration.zsh").path
            return Environment(command: shell.isEmpty ? nil : shell, variables: variables)
        case "bash" where shell.split(separator: " ").count <= 1:
            // A plain bash: read our rc file, which loads the user's. libghostty starts commands
            // as login shells (`exec -l`), which would skip --rcfile, so go through env.
            if shell.isEmpty { variables["BRIDGE_LOGIN"] = "1" }
            let program = shell.isEmpty ? loginShell : shell
            let rc = directory.appendingPathComponent("integration.bash").path
            return Environment(
                command: "/usr/bin/env \(Launch.quote(program)) --rcfile \(Launch.quote(rc)) -i",
                variables: variables)
        default:
            return Environment(command: shell.isEmpty ? nil : shell, variables: variables)
        }
    }

    /// Write the scripts and the prompt files for `settings`.
    public static func install(_ settings: Settings) throws {
        let fm = FileManager.default
        let zsh = directory.appendingPathComponent("zsh")
        try fm.createDirectory(at: zsh, withIntermediateDirectories: true)
        try write(zshenv, to: zsh.appendingPathComponent(".zshenv"))
        for (name, script) in zshWrappers {
            try write("# Generated by Bridge.\n" + script, to: zsh.appendingPathComponent(name))
        }
        try write(integrationZsh, to: directory.appendingPathComponent("integration.zsh"))
        try write(integrationBash, to: directory.appendingPathComponent("integration.bash"))
        try write(assistZsh, to: directory.appendingPathComponent("assist.zsh"))
        try writePrompts(settings)
    }

    /// Rewrite the prompt files; running shells pick them up at their next prompt.
    public static func writePrompts(_ settings: Settings) throws {
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let starshipConfig = directory.appendingPathComponent("starship.toml").path
        try write(zshPromptFile(settings, starshipConfig: starshipConfig), to: directory.appendingPathComponent("prompt.zsh"))
        try write(bashPromptFile(settings, starshipConfig: starshipConfig), to: directory.appendingPathComponent("prompt.bash"))
    }

    private static func write(_ text: String, to url: URL) throws {
        // Skip unchanged files, so running shells don't see a change for nothing.
        if let existing = try? String(contentsOf: url, encoding: .utf8), existing == text { return }
        try text.write(to: url, atomically: true, encoding: .utf8)
    }

    /// Whether `starship` is installed (also outside the app's minimal PATH).
    public static var starshipInstalled: Bool {
        let path = ProcessInfo.processInfo.environment["PATH"] ?? ""
        let dirs = path.split(separator: ":").map(String.init)
            + ["/opt/homebrew/bin", "/usr/local/bin", Paths.home + "/.cargo/bin", Paths.home + "/.local/bin"]
        return dirs.contains { FileManager.default.isExecutableFile(atPath: $0 + "/starship") }
    }

    // MARK: - Prompt files

    static func zshPromptFile(_ settings: Settings, starshipConfig: String) -> String {
        var file = "# Generated by Bridge from your prompt settings.\n"
        let patternBlock: String
        if let pattern = settings.promptStyle.template(custom: settings.promptTemplate) {
            let (prompt, git) = PromptTemplate.zsh(pattern)
            patternBlock = (git ? "setopt prompt_subst\n_bridge_git_branch\n" : "")
                + "PROMPT=\(Launch.singleQuote(prompt))\nRPROMPT=''\n_bridge_overridden=1\n"
        } else {
            patternBlock = """
            if (( _bridge_overridden )); then
              PROMPT="$_bridge_user_prompt"
              RPROMPT="$_bridge_user_rprompt"
              _bridge_overridden=0
            fi

            """
        }
        if settings.promptStyle == .starship {
            // Start Starship once it is installed (no ~/.zshrc changes needed). Without a Starship
            // config of the user's own, use the preset that needs no special icon fonts.
            file += """
            if (( ! ${_bridge_starship:-0} )) && whence -p starship >/dev/null; then
              if [[ -z "${STARSHIP_CONFIG-}" && ! -e "${XDG_CONFIG_HOME:-$HOME/.config}/starship.toml" ]]; then
                export STARSHIP_CONFIG=\(Launch.singleQuote(starshipConfig))
                [[ -e "$STARSHIP_CONFIG" ]] || starship preset no-nerd-font -o "$STARSHIP_CONFIG" 2>/dev/null
              fi
              if [[ "$_bridge_user_prompt" == *starship* ]]; then
                typeset -g _bridge_starship_prompt="$_bridge_user_prompt" _bridge_starship_rprompt="$_bridge_user_rprompt"
              else
                eval "$(starship init zsh)"
                typeset -g _bridge_starship_prompt="$PROMPT" _bridge_starship_rprompt="$RPROMPT"
              fi
              typeset -g _bridge_starship=1
            fi
            if (( ${_bridge_starship:-0} )); then
              setopt prompt_subst
              PROMPT="$_bridge_starship_prompt"
              RPROMPT="$_bridge_starship_rprompt"
              _bridge_overridden=1
            else
            \(patternBlock)fi

            """
        } else {
            file += patternBlock
        }
        file += settings.hidePartialLineMarker ? "PROMPT_EOL_MARK=''\n" : "PROMPT_EOL_MARK='%B%S%#%s%b'\n"
        return file
    }

    static func bashPromptFile(_ settings: Settings, starshipConfig: String) -> String {
        var file = "# Generated by Bridge from your prompt settings.\n"
        let patternBlock: String
        if let pattern = settings.promptStyle.template(custom: settings.promptTemplate) {
            let (prompt, git) = PromptTemplate.bash(pattern)
            patternBlock = (git ? "_bridge_git_branch\n" : "") + "PS1=\(Launch.singleQuote(prompt))\n_bridge_overridden=1\n"
        } else {
            patternBlock = """
            if [[ "$_bridge_overridden" == 1 ]]; then
              PS1="$_bridge_user_ps1"
              _bridge_overridden=0
            fi

            """
        }
        if settings.promptStyle == .starship {
            file += """
            if [[ "${_bridge_starship:-0}" != 1 ]] && command -v starship >/dev/null; then
              if [[ -z "${STARSHIP_CONFIG-}" && ! -e "${XDG_CONFIG_HOME:-$HOME/.config}/starship.toml" ]]; then
                export STARSHIP_CONFIG=\(Launch.singleQuote(starshipConfig))
                [[ -e "$STARSHIP_CONFIG" ]] || starship preset no-nerd-font -o "$STARSHIP_CONFIG" 2>/dev/null
              fi
              [[ "$_bridge_user_ps1" == *starship* ]] || eval "$(starship init bash)"
              _bridge_starship=1
            fi
            if [[ "${_bridge_starship:-0}" != 1 ]]; then
            \(patternBlock)fi

            """
        } else {
            file += patternBlock
        }
        return file
    }

    // MARK: - Scripts

    /// Our `ZDOTDIR` points here: restore the user's `ZDOTDIR` so zsh reads their own startup
    /// files next, source their `.zshenv`, then load the integration.
    ///
    /// A sandboxed session (with `BRIDGE_HISTFILE`) keeps our `ZDOTDIR`: the wrappers below load
    /// the user's startup files and then point `HISTFILE` at the session's own history, so the
    /// user's history (which the sandbox can't read) is never opened.
    static let zshenv = #"""
    # Generated by Bridge. Restores your ZDOTDIR and loads your own startup files.
    if [[ -n "${BRIDGE_HISTFILE-}" ]]; then
      typeset -g _bridge_user_zdotdir="${BRIDGE_USER_ZDOTDIR:-$HOME}"
      unset BRIDGE_USER_ZDOTDIR
      [[ -r "$_bridge_user_zdotdir/.zshenv" ]] && source "$_bridge_user_zdotdir/.zshenv"
    else
      if [[ -n "${BRIDGE_USER_ZDOTDIR-}" ]]; then
        export ZDOTDIR="$BRIDGE_USER_ZDOTDIR"
      else
        unset ZDOTDIR
      fi
      unset BRIDGE_USER_ZDOTDIR
      [[ -r "${ZDOTDIR:-$HOME}/.zshenv" ]] && source "${ZDOTDIR:-$HOME}/.zshenv"
    fi
    if [[ -o interactive && -r "${BRIDGE_INTEGRATION-}" ]]; then
      source "$BRIDGE_INTEGRATION"
    fi

    """#

    /// The rest of a sandboxed session's startup files: each loads the user's own, and the
    /// history file is set after them (and before zsh reads it).
    static let zshWrappers: [(String, String)] = [
        (".zprofile", #"[[ -r "$_bridge_user_zdotdir/.zprofile" ]] && source "$_bridge_user_zdotdir/.zprofile""# + "\n"),
        (".zshrc", #"""
        [[ -r "$_bridge_user_zdotdir/.zshrc" ]] && source "$_bridge_user_zdotdir/.zshrc"
        [[ -n "${BRIDGE_HISTFILE-}" ]] && HISTFILE="$BRIDGE_HISTFILE"

        """#),
        (".zlogin", #"""
        [[ -r "$_bridge_user_zdotdir/.zlogin" ]] && source "$_bridge_user_zdotdir/.zlogin"
        [[ -n "${BRIDGE_HISTFILE-}" ]] && HISTFILE="$BRIDGE_HISTFILE"

        """#),
        (".zlogout", #"[[ -r "$_bridge_user_zdotdir/.zlogout" ]] && source "$_bridge_user_zdotdir/.zlogout""# + "\n"),
    ]

    static let integrationZsh = #"""
    # Generated by Bridge: reports prompts and commands, and applies prompt settings after your
    # own startup files.
    typeset -g _bridge_overridden=0 _bridge_fd= _bridge_cmd_running=0

    # The connection to the app: one message is fields joined by U+001F, ended by NUL.
    zmodload zsh/net/socket 2>/dev/null
    _bridge_connect() {
      [[ -n $_bridge_fd || -z ${BRIDGE_SOCKET-} ]] && return
      zsocket "$BRIDGE_SOCKET" 2>/dev/null || return
      typeset -g _bridge_fd=$REPLY
      _bridge_send hello "${BRIDGE_PANE-}" zsh
    }
    _bridge_send() {
      [[ -n $_bridge_fd ]] || return 1
      local IFS=$'\x1f'
      print -rn -u $_bridge_fd -- "$*"$'\0' 2>/dev/null || { exec {_bridge_fd}>&-; _bridge_fd=; return 1 }
    }

    _bridge_prompt() {
      local exit_status=$?
      _bridge_connect
      [[ -r "${BRIDGE_PROMPT_DIR-}/prompt.zsh" ]] && source "$BRIDGE_PROMPT_DIR/prompt.zsh"
      if (( _bridge_cmd_running )); then
        _bridge_cmd_running=0
        builtin print -rn -- $'\e]133;D;'"$exit_status"$'\a'
      fi
      _bridge_send prompt "$exit_status" "$PWD" "$PATH"
      # The folder for libghostty (new tabs and splits start here) and the window title.
      builtin print -rn -- $'\e]7;file://'"${HOST}${PWD// /%20}"$'\a'
      builtin print -rn -- $'\e]2;'"${PWD/#$HOME/~}"$'\a'
      if [[ -n "${BRIDGE_PROJECT_ROOT-}" ]]; then
        # A sandboxed session: the project folder stands in for the home folder in the prompt.
        local root="${BRIDGE_PROJECT_ROOT%/}" here="$PWD"
        if [[ $here == "$root" ]]; then
          typeset -g _bridge_pwd='~' _bridge_dir='~'
        elif [[ $here == "$root"/* ]]; then
          typeset -g _bridge_pwd="~/${here#$root/}" _bridge_dir="${here:t}"
        else
          typeset -g _bridge_pwd="${here/#$HOME/~}" _bridge_dir="${here:t}"
        fi
        _bridge_pwd=${_bridge_pwd//\%/%%}
        _bridge_dir=${_bridge_dir//\%/%%}
        setopt prompt_subst
        PROMPT=${PROMPT//'%1~'/'${_bridge_dir}'}
        PROMPT=${PROMPT//'%~'/'${_bridge_pwd}'}
      fi
      # Prompt start and end marks (OSC 133 A and B), re-added each time so they never pile up.
      local start=$'%{\e]133;A\a%}' end=$'%{\e]133;B\a%}'
      PROMPT="${PROMPT#"$start"}"
      PROMPT="$start${PROMPT%"$end"}$end"
    }

    _bridge_preexec() {
      _bridge_cmd_running=1
      builtin print -rn -- $'\e]133;C\a'
      builtin print -rn -- $'\e]2;'"${1//[$'\a\e']/}"$'\a'
      _bridge_send cmd "$1" "$PWD"
    }

    # Current git branch (with a leading space) in $_bridge_git. Reads .git/HEAD directly instead
    # of running git, so it costs microseconds per prompt.
    _bridge_git_branch() {
      typeset -g _bridge_git=''
      local dir=$PWD git head
      while true; do
        git=$dir/.git
        if [[ -f $git ]]; then
          read -r head < $git
          git=${head#gitdir: }
          [[ $git == /* ]] || git=$dir/$git
        fi
        if [[ -r $git/HEAD ]]; then
          read -r head < $git/HEAD
          if [[ $head == 'ref: refs/heads/'* ]]; then
            head=${head#ref: refs/heads/}
          else
            head=${head[1,7]}
          fi
          _bridge_git=" ${head//\%/%%}"
          return
        fi
        [[ $dir == / || -z $dir ]] && return
        dir=${dir:h}
      done
    }

    _bridge_setup() {
      # Runs once at the first prompt, when ~/.zshrc and friends have been loaded.
      precmd_functions=(${precmd_functions:#_bridge_setup})
      typeset -g _bridge_user_prompt="$PROMPT" _bridge_user_rprompt="$RPROMPT"
      # Keep the prompt hook last so it wins over prompt frameworks that also use precmd.
      precmd_functions=(${precmd_functions:#_bridge_prompt} _bridge_prompt)
      bindkey -M emacs '^[[3~' delete-char 2>/dev/null
      if [[ -n "${BRIDGE_PROJECT_ROOT-}" ]]; then
        # In a sandboxed session `cd` and `cd ~` go to the project folder, not the real home.
        unalias cd 2>/dev/null
        cd() {
          if (( $# == 0 )) || [[ $1 == "$HOME" ]]; then
            builtin cd "${BRIDGE_PROJECT_ROOT%/}"
          elif [[ $1 == "$HOME"/* ]]; then
            builtin cd "${BRIDGE_PROJECT_ROOT%/}/${1#$HOME/}" "${@:2}"
          else
            builtin cd "$@"
          fi
        }
      fi
      # Word movement and deletion (⌥← ⌥→ ⌥⌫) stop at punctuation such as / . - _; a WORDCHARS
      # of your own is left alone.
      [[ $WORDCHARS == '*?_-.[]~=/&;!#$%^(){}<>' ]] && WORDCHARS=''
      [[ -r "${BRIDGE_PROMPT_DIR-}/assist.zsh" ]] && source "$BRIDGE_PROMPT_DIR/assist.zsh"
      _bridge_prompt
    }

    typeset -ga precmd_functions preexec_functions
    precmd_functions+=(_bridge_setup)
    preexec_functions+=(_bridge_preexec)

    """#

    /// zsh suggestions and completions, from the app: before each redraw the line is sent and
    /// the app answers with the gray rest of a suggestion, drawn by zsh itself so it lines up
    /// exactly. Tab asks the app for completions (one is inserted, several open the app's menu),
    /// falling back to zsh's own completion.
    static let assistZsh = #"""
    # Generated by Bridge: suggestions and completions.
    typeset -g _bridge_last_buffer= _bridge_last_cursor=-1

    # Send a request and wait briefly for the reply (in $REPLY).
    _bridge_request() {
      _bridge_send "$@" || return 1
      IFS= read -r -d $'\0' -t 0.25 -u $_bridge_fd REPLY || return 1
    }

    # Before each redraw: when the line changed, ask for a suggestion and show it in gray.
    _bridge_redraw() {
      [[ -n $_bridge_fd ]] || return
      [[ $BUFFER == "$_bridge_last_buffer" && $CURSOR == $_bridge_last_cursor ]] && return
      _bridge_last_buffer=$BUFFER _bridge_last_cursor=$CURSOR
      POSTDISPLAY=
      region_highlight=("${(@)region_highlight:#*memo=bridge*}")
      if (( CURSOR == ${#BUFFER} )) && [[ -n $BUFFER ]] && _bridge_request suggest "$BUFFER" "$PWD" "$PATH"; then
        if [[ -n $REPLY ]]; then
          POSTDISPLAY=$REPLY
          region_highlight+=("${#BUFFER} $(( ${#BUFFER} + ${#POSTDISPLAY} )) fg=8,memo=bridge")
        fi
      else
        _bridge_send line "$LBUFFER" "$PWD" "$PATH"
      fi
    }

    # Accept the whole suggestion (→, End, ⌃F, ⌘→), or move as usual.
    _bridge_accept() {
      if [[ -n $POSTDISPLAY ]] && (( CURSOR == ${#BUFFER} )); then
        BUFFER+=$POSTDISPLAY
        POSTDISPLAY=
        CURSOR=${#BUFFER}
      else
        zle .$WIDGET
      fi
    }

    # Accept the suggestion's next word (⌥→, ⌃→), or move as usual.
    _bridge_accept_word() {
      if [[ -n $POSTDISPLAY ]] && (( CURSOR == ${#BUFFER} )) && [[ $POSTDISPLAY =~ '^[[:space:]]*[^[:space:]/._-]*[/._-]?' ]]; then
        BUFFER+=$MATCH
        POSTDISPLAY=${POSTDISPLAY#"$MATCH"}
        CURSOR=${#BUFFER}
      else
        zle .$WIDGET
      fi
    }

    # Tab: Bridge's completions; one is inserted, several open the menu, none falls back to zsh.
    _bridge_complete() {
      if [[ -n $_bridge_fd ]] && _bridge_request complete "$LBUFFER" "$PWD" "$PATH"; then
        local -a parts=("${(@ps:\x1f:)REPLY}")
        case $parts[1] in
          replace)
            LBUFFER=${LBUFFER[1,-$(( parts[2] + 1 ))]}$parts[3]
            return ;;
          menu)
            return ;;
        esac
      fi
      zle expand-or-complete
    }

    zle -N forward-char _bridge_accept
    zle -N end-of-line _bridge_accept
    zle -N vi-forward-char _bridge_accept
    zle -N vi-end-of-line _bridge_accept
    zle -N forward-word _bridge_accept_word
    zle -N emacs-forward-word _bridge_accept_word
    zle -N _bridge_complete
    bindkey '^I' _bridge_complete
    bindkey '^[[1;5C' forward-word
    autoload -Uz add-zle-hook-widget
    add-zle-hook-widget line-pre-redraw _bridge_redraw

    """#

    static let integrationBash = #"""
    # Generated by Bridge: loads your startup files, then reports prompts and applies prompt
    # settings.
    if [[ -n "${BRIDGE_LOGIN-}" ]]; then
      unset BRIDGE_LOGIN
      [[ -r /etc/profile ]] && . /etc/profile
      for _bridge_rc in "$HOME/.bash_profile" "$HOME/.bash_login" "$HOME/.profile"; do
        if [[ -r "$_bridge_rc" ]]; then
          . "$_bridge_rc"
          break
        fi
      done
      unset _bridge_rc
    elif [[ -r "$HOME/.bashrc" ]]; then
      . "$HOME/.bashrc"
    fi
    # A sandboxed session keeps its own history (bash reads it after this file).
    [[ -n "${BRIDGE_HISTFILE-}" ]] && HISTFILE="$BRIDGE_HISTFILE"

    _bridge_git_branch() {
      _bridge_git=''
      local dir=$PWD git head
      while true; do
        git=$dir/.git
        if [[ -f $git ]]; then
          read -r head < "$git"
          git=${head#gitdir: }
          [[ $git == /* ]] || git=$dir/$git
        fi
        if [[ -r $git/HEAD ]]; then
          read -r head < "$git/HEAD"
          if [[ $head == 'ref: refs/heads/'* ]]; then
            head=${head#ref: refs/heads/}
          else
            head=${head:0:7}
          fi
          _bridge_git=" $head"
          return
        fi
        [[ $dir == / || -z $dir ]] && return
        dir=${dir%/*}
        [[ -z $dir ]] && dir=/
      done
    }

    # bash has no unix sockets: the helper program delivers the messages.
    _bridge_send() {
      [[ -n "${BRIDGE_HELPER-}" && -n "${BRIDGE_SOCKET-}" ]] || return
      "$BRIDGE_HELPER" send "$BRIDGE_SOCKET" hello "${BRIDGE_PANE-}" bash -- "$@" 2>/dev/null
    }

    _bridge_user_ps1="$PS1"
    _bridge_overridden=0
    _bridge_last_histcmd=
    _bridge_prompt() {
      local exit_status=$?
      [[ -r "${BRIDGE_PROMPT_DIR-}/prompt.bash" ]] && . "$BRIDGE_PROMPT_DIR/prompt.bash"
      # The command that just ran, from bash's history (once per history number).
      local number command
      number=$(HISTTIMEFORMAT= builtin history 1 | sed -E 's/^ *([0-9]+).*/\1/')
      if [[ -n "$number" && "$number" != "$_bridge_last_histcmd" && -n "$_bridge_last_histcmd" ]]; then
        command=$(HISTTIMEFORMAT= builtin history 1 | sed -E 's/^ *[0-9]+ +//')
        _bridge_send done "$exit_status" "$command" "$PWD" "$PATH"
        printf '\e]133;D;%s\a' "$exit_status"
      else
        _bridge_send prompt "$exit_status" "$PWD" "$PATH"
      fi
      _bridge_last_histcmd=$number
      printf '\e]7;file://%s%s\a' "$HOSTNAME" "${PWD// /%20}"
      printf '\e]2;%s\a' "${PWD/#$HOME/\~}"
      local start='\[\e]133;A\a\]' end='\[\e]133;B\a\]'
      PS1="${PS1#"$start"}"
      PS1="$start${PS1%"$end"}$end"
      return $exit_status
    }
    PROMPT_COMMAND="${PROMPT_COMMAND:+$PROMPT_COMMAND;}_bridge_prompt"

    """#
}

extension Launch {
    /// Single-quote a string for zsh or bash, always.
    public static func singleQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }
}
